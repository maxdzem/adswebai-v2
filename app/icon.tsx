import { ImageResponse } from "next/og";

/**
 * Фавиконка генерируется в PNG на сборке.
 *
 * Раньше здесь лежал icon.svg, но у него был только viewBox без явных
 * width/height — растеризаторы (в частности превью на Vercel) не могли
 * определить размер и падали с ошибкой рендера. PNG понимают все
 * без исключений.
 *
 * Рисунок: фирменный розовый квадрат #FF0091 (острые углы, без
 * borderRadius — тот же язык формы, что у кубика-переключателя в шапке)
 * с чёрным #000000 равносторонним треугольником вершиной вниз поверх.
 * Пропорции взяты у логотипа Vercel (равносторонний, высота = ширина ×
 * √3/2), только перевёрнутые.
 *
 * Всё рисуется одним инлайновым <svg> с честным <path>. До этого были
 * две неудачные попытки:
 *   1. border-top/left/right на блоке width:0;height:0 — Satori (движок
 *      ImageResponse) не схлопывает бордеры и рисовал чёрный квадрат;
 *   2. clip-path: polygon(...) на залитом блоке — форма верная, но
 *      Satori режет по пикселям без сглаживания, диагонали выходили
 *      «лесенкой», плюс блок вставал на полпикселя мимо центра.
 * <path> растеризуется через resvg с антиалиасингом, а координаты
 * задаются явно — никакого промаха по центру.
 */

export const size = { width: 64, height: 64 };
export const contentType = "image/png";

// Равносторонний треугольник вершиной вниз в холсте 64×64:
// ширина 40 → высота 40 × √3/2 ≈ 34.64, отцентрован по обеим осям.
const TRIANGLE = "M32 49.32 L52 14.68 L12 14.68 Z";

export default function Icon() {
  return new ImageResponse(
    (
      <div style={{ width: "100%", height: "100%", display: "flex" }}>
        <svg
          width="64"
          height="64"
          viewBox="0 0 64 64"
          xmlns="http://www.w3.org/2000/svg"
        >
          <rect width="64" height="64" fill="#FF0091" />
          <path d={TRIANGLE} fill="#000000" />
        </svg>
      </div>
    ),
    { ...size }
  );
}
